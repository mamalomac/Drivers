const FormatInfo* formatTable(size_t* count) {
    *count = sizeof(g_formats) / sizeof(g_formats[0]);
    return g_formats;
}

const FormatInfo* findFormat(VkFormat f) {
    for (const auto& e : g_formats)
        if (e.vk == f) return &e;
    return nullptr;
}

